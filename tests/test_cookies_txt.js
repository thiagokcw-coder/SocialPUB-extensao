const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const ctx = vm.createContext({});
vm.runInContext(fs.readFileSync('cookies.js', 'utf8'), ctx);
const ler = t => JSON.parse(JSON.stringify(ctx.spLerCookiesTodas(t)));
const cookie = (domain, name='sessionid', value='ficticio') => ({domain,name,value});
const all = ['x.com','instagram.com','tiktok.com','threads.net','facebook.com'].map(d=>cookie('.'+d));
assert.equal(Object.keys(ler(all.map(c=>JSON.stringify([c])).join('\n\n')).redes).length,5);
assert.equal(Object.keys(ler(JSON.stringify({cookies:all})).redes).length,5);
assert.equal(ler('\ufeff'+JSON.stringify(all)).redes.facebook.cookies.length,1);
const special = cookie('.facebook.com','xs','a"b\\c}[]{');
assert.equal(ler(JSON.stringify([special])).redes.facebook.cookies[0].value,special.value);
const net = '# Netscape HTTP Cookie File\n#HttpOnly_.facebook.com\tTRUE\t/\tTRUE\t0\txs\tfake\n.instagram.com\tTRUE\t/\tTRUE\t4102444800\tsessionid\tfake';
assert.equal(ler(net).redes.facebook.cookies[0].httpOnly,true);
assert.equal(ler(net).redes.instagram.cookies[0].expirationDate,4102444800);
const mixed = [all[0], all[0], cookie('x.com.evil.test'), {...all[1],expirationDate:1}];
assert.deepEqual(ler(JSON.stringify(mixed)).ignorados,{outros:1,expirados:1,duplicados:1});
assert.throws(()=>ler(JSON.stringify([all[0],{...all[0],value:'outro'}])),/conflitantes/);
assert.throws(()=>ler('sessionid=SEGREDO'),/sem domínio/);
assert.throws(()=>ler('[{"value":"SEGREDO"'), e=>!e.message.includes('SEGREDO'));
assert.throws(()=>ler(JSON.stringify([{name:'xs',value:'ficticio'}])),/sem domínio/);
assert.throws(()=>ler(JSON.stringify([cookie('facebook.com.evil.test')])),/nenhum cookie/);
assert.throws(()=>ler(''),/vazio/);
assert.throws(()=>ler(net+'\nlinha inválida'),/linha 4/);
assert.deepEqual(ler(JSON.stringify([cookie('www.facebook.com','xs')])).redes.facebook.faltando,['c_user']);
console.log('OK: TXT JSON concatenado, Netscape, cinco redes, domínios, validade, duplicados e erros sem credenciais');
